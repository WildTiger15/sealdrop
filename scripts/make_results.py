"""Build outputs/results.md from real run outputs only (no hand typed numbers).

Inputs:
  target/criterion/**/new/estimates.json   (cargo bench -p sealdrop-core)
  outputs/core-tests.txt                   (cargo test -p sealdrop-core -- --nocapture)
  outputs/fuzz-<target>.log                (cargo +nightly fuzz run ... -print_final_stats=1)
  outputs/browser-bench.json, outputs/e2e.txt   (node web/e2e/e2e.mjs)

Run from the repo root:  python -I scripts/make_results.py
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "outputs"
CRIT = ROOT / "target" / "criterion"


def median_ns(group, bench, size=None):
    p = CRIT / group / bench
    if size is not None:
        p = p / str(size)
    est = json.loads((p / "new" / "estimates.json").read_text())
    return est["median"]["point_estimate"]


def ms(ns):
    return f"{ns / 1e6:.3f} ms"


def us(ns):
    return f"{ns / 1e3:.1f} µs"


def mibs(size, ns):
    return size / (1 << 20) / (ns / 1e9)


lines = []
w = lines.append

w("# SealDrop results\n")
w("Every number below was produced by a real run on the author's machine and is regenerated by")
w("`scripts/make_results.py` from the raw outputs in this folder and `target/criterion`.")
w("Laptop numbers vary between runs (power management, background load); treat them as rough.\n")

# ---- tests ----
tests = (OUT / "core-tests.txt").read_text(encoding="utf-8", errors="replace")
xw = re.search(r"X-Wing official vectors passed: (\d+)/(\d+)", tests)
kg = re.search(r"ML-DSA-65 ACVP keyGen passed: (\d+)/(\d+)", tests)
sg = re.search(r"ML-DSA-65 ACVP sigGen passed: (\d+)/(\d+)", tests)
sv = re.search(r"ML-DSA-65 ACVP sigVer passed: (\d+)/(\d+)", tests)
flips = re.search(r"bit flips rejected: (\d+)/(\d+)", tests)
total_tests = sum(int(m) for m in re.findall(r"test result: ok\. (\d+) passed", tests))
failed = sum(int(m) for m in re.findall(r"(\d+) failed", tests))
official = sum(int(m.group(1)) for m in (xw, kg, sg, sv))
official_total = sum(int(m.group(2)) for m in (xw, kg, sg, sv))

w("## Correctness\n")
w("| Check | Result |")
w("|---|---|")
w(f"| X-Wing draft-11 Appendix C vectors | {xw.group(1)}/{xw.group(2)} |")
w(f"| NIST ACVP ML-DSA-65 keyGen | {kg.group(1)}/{kg.group(2)} |")
w(f"| NIST ACVP ML-DSA-65 sigGen | {sg.group(1)}/{sg.group(2)} |")
w(f"| NIST ACVP ML-DSA-65 sigVer (36 of them must-reject) | {sv.group(1)}/{sv.group(2)} |")
w(f"| **Official vectors total** | **{official}/{official_total}** |")
w(f"| One bit flipped, in every byte position of a sealed file: rejected | {flips.group(1)}/{flips.group(2)} |")
w(f"| Rust core tests | {total_tests} passed, {failed} failed |")
e2e = (OUT / "e2e.txt").read_text(encoding="utf-8")
oks = e2e.count("  ok  ")
w(f"| End to end browser test (passkeys, PRF, sharing, fallback) | {oks} checks passed, {'PASSED' if 'ZERO KNOWLEDGE CHECK PASSED' in e2e else 'see e2e.txt'} |")
zk = re.search(r"ZERO KNOWLEDGE CHECK (\w+)[^\n]*", e2e)
w(f"| Zero knowledge database dump | {zk.group(0) if zk else 'not run'} |\n")

# ---- fuzzing ----
w("## Fuzzing (cargo-fuzz / libFuzzer, AddressSanitizer, Windows MSVC)\n")
w("| Target | Time | Executions | Exec/s | Crashes |")
w("|---|---|---|---|---|")
fuzz_total = 0
fuzz_crashes = 0
for t in ["decrypt", "decapsulate", "verify"]:
    p = OUT / f"fuzz-{t}.log"
    if not p.exists():
        w(f"| {t} | not run | | | |")
        continue
    log = p.read_text(encoding="utf-8", errors="replace")
    ex = re.search(r"stat::number_of_executed_units:\s*(\d+)", log)
    tm = re.search(r"Done (\d+) runs in (\d+) second", log)
    crashed = bool(re.search(r"==ERROR|SUMMARY: libFuzzer|deadly signal|Test unit written to", log)) or "exit=0" not in log
    n = int(ex.group(1)) if ex else 0
    secs = int(tm.group(2)) if tm else 0
    fuzz_total += n
    fuzz_crashes += int(crashed)
    rate = f"{n / secs:.0f}" if secs else "?"
    w(f"| {t} | {secs // 60} min | {n:,} | {rate} | {'YES, see log' if crashed else 0} |")
w(f"| **total** | | **{fuzz_total:,}** | | **{fuzz_crashes}** |\n")

# ---- benchmarks ----
w("## Benchmarks (criterion, native, release build; median)\n")
w("### Key exchange and signatures\n")
w("| Operation | Post quantum | Classic | PQ / classic |")
w("|---|---|---|---|")
pairs = [
    ("KEM keygen", ("kem", "xwing_keygen"), ("kem", "x25519_keygen")),
    ("KEM encapsulate", ("kem", "xwing_encapsulate"), ("kem", "x25519_encapsulate")),
    ("KEM decapsulate", ("kem", "xwing_decapsulate"), ("kem", "x25519_decapsulate")),
    ("Signature keygen", ("sig", "mldsa65_keygen"), ("sig", "ed25519_keygen")),
    ("Sign", ("sig", "mldsa65_sign"), ("sig", "ed25519_sign")),
    ("Verify", ("sig", "mldsa65_verify"), ("sig", "ed25519_verify")),
]
vals = {}
for label, pq, cl in pairs:
    a, b = median_ns(*pq), median_ns(*cl)
    vals[label] = (a, b)
    w(f"| {label} | {us(a)} | {us(b)} | {a / b:.1f}× |")
w("\nPost quantum = X-Wing (X25519 + ML-KEM-768) and ML-DSA-65; classic = X25519 alone and Ed25519.\n")

w("### File encryption throughput\n")
w("| File size | SealDrop seal | SealDrop open | Classic seal (X25519 + Ed25519, same format) | Classic, no signature | SealDrop / classic seal |")
w("|---|---|---|---|---|---|")
ratios = {}
for size in [65536, 1048576, 16777216]:
    s = median_ns("file", "sealdrop_seal", size)
    o = median_ns("file", "sealdrop_open", size)
    c = median_ns("file", "classic_x25519_ed25519_seal", size)
    n = median_ns("file", "classic_x25519_encrypt", size)
    ratios[size] = s / c
    w(f"| {size // 1024} KiB | {ms(s)} ({mibs(size, s):.1f} MiB/s) | {ms(o)} ({mibs(size, o):.1f} MiB/s) | "
      f"{ms(c)} ({mibs(size, c):.1f} MiB/s) | {ms(n)} ({mibs(size, n):.1f} MiB/s) | {s / c:.2f}× |")
w("\nMost of the gap between \"classic, no signature\" and both signed variants is SHA3-256 over the whole")
w("ciphertext (the signed body hash), not post quantum cost. The PQ-only cost is the column \"SealDrop / classic seal\".\n")

bb = json.loads((OUT / "browser-bench.json").read_text())
w("### In the browser (WebAssembly)\n")
w(f"Microsoft Edge {bb['browser']} (headless, Playwright), 1 MiB file, median of 10: "
  f"seal {bb['seal_ms']:.1f} ms ({bb['seal_mib_s']:.1f} MiB/s), open {bb['open_ms']:.1f} ms ({bb['open_mib_s']:.1f} MiB/s). "
  "WASM build size: see `web/dist/assets/*.wasm`.\n")

w("## Sizes (bytes)\n")
w("Fixed by the specifications and asserted by the code's constants and tests.\n")
w("| Item | Post quantum | Classic |")
w("|---|---|---|")
w("| KEM public key | 1216 (X-Wing) | 32 (X25519) |")
w("| KEM ciphertext | 1120 (X-Wing) | 32 (X25519 ephemeral key) |")
w("| Shared secret | 32 | 32 |")
w("| Signature public key | 1952 (ML-DSA-65) | 32 (Ed25519) |")
w("| Signature | 3309 (ML-DSA-65) | 64 (Ed25519) |")
w("| SealDrop per-file overhead | 4522 + 16 per 64 KiB chunk | n/a |")
m = re.search(r"\((\d+) bytes\) to bob: encrypted \+ signed in ([\d.]+) ms, (\d+) bytes overhead", e2e)
if m:
    w(f"\nMeasured in the e2e run: an {m.group(1)} byte file became {int(m.group(1)) + int(m.group(3))} bytes "
      f"({m.group(3)} bytes overhead = 4522 + 16 × 1 chunk).\n")

w("## Resume numbers (from the tables above)\n")
w(f"* N (official test vectors passed) = **{official}**")
w(f"* E (fuzzing executions, zero crashes = {fuzz_crashes == 0}) = **{fuzz_total:,}**")
w(f"* X (hybrid key exchange: X-Wing encapsulate + decapsulate) = **{(vals['KEM encapsulate'][0] + vals['KEM decapsulate'][0]) / 1e6:.2f} ms**")
w(f"* S (ML-DSA-65 sign) = **{vals['Sign'][0] / 1e6:.2f} ms**")
y = mibs(16777216, median_ns("file", "sealdrop_seal", 16777216))
w(f"* Y (file encryption, 16 MiB, full seal incl. signature) = **{y:.0f} MiB/s**")
w(f"* Z (SealDrop seal vs same-format classic X25519 + Ed25519 seal, 16 MiB) = **{ratios[16777216]:.2f}×**")

extra = OUT / "results-extra.md"
if extra.exists():
    w("\n" + extra.read_text(encoding="utf-8"))

(OUT / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote outputs/results.md")


# ---- README.md from scripts/README.template.md, with the same numbers ----
def block(lines_):
    return "\n".join(l.rstrip() for l in lines_)


summary = {
    "N": str(official), "XW": f"{xw.group(1)}/{xw.group(2)}",
    "MLDSA": f"{int(kg.group(1)) + int(sg.group(1)) + int(sv.group(1))}/{int(kg.group(2)) + int(sg.group(2)) + int(sv.group(2))}",
    "E": f"{fuzz_total:,}", "C": str(fuzz_crashes), "FLIPS": f"{flips.group(1)}/{flips.group(2)}",
    "X": f"{(vals['KEM encapsulate'][0] + vals['KEM decapsulate'][0]) / 1e6:.2f} ms",
    "X_CL": f"{(vals['KEM encapsulate'][1] + vals['KEM decapsulate'][1]) / 1e6:.2f} ms",
    "S": f"{vals['Sign'][0] / 1e6:.2f} ms", "V": f"{vals['Verify'][0] / 1e6:.2f} ms",
    "S_CL": f"{vals['Sign'][1] / 1e6:.3f} ms", "V_CL": f"{vals['Verify'][1] / 1e6:.3f} ms",
    "Y": f"{y:.0f} MiB/s", "Z": f"{ratios[16777216]:.2f}×",
    "BROWSER": f"{bb['seal_ms']:.1f} ms / {bb['open_ms']:.1f} ms",
    "E2E": f"{oks} checks passed" + (", zero knowledge check passed" if zk and zk.group(1) == "PASSED" else ""),
    "QUICKSTART": block((OUT / "example-quickstart.txt").read_text(encoding="utf-8").strip().splitlines()),
    "KAT_LINES": block(re.findall(r"(?:X-Wing official vectors|ML-DSA-65 ACVP \w+) passed: \d+/\d+", tests)),
    "E2E_LINES": block(l for l in e2e.strip().splitlines() if not l.startswith("  prefix")),
}
(OUT / "summary.json").write_text(json.dumps({k: v for k, v in summary.items() if "\n" not in v}, indent=1), encoding="utf-8")
text = (ROOT / "scripts" / "README.template.md").read_text(encoding="utf-8")
for k, v in summary.items():
    text = text.replace("{" + k + "}", v)
left = re.findall(r"\{[A-Z_]+\}", text)
if left:
    sys.exit(f"unfilled README placeholders: {left}")
(ROOT / "README.md").write_text(text, encoding="utf-8")
print("wrote README.md from scripts/README.template.md")
