"""The agent's own identity and where it is kept.

State lives in one private file (default `mcp/state/agent.json`, or
$SEALDROP_AGENT_HOME/agent.json), created with owner-only permissions:

    name        human name for the agent
    secret      64 byte SealDrop identity (X-Wing seed || ML-DSA seed), base64
    auth_key    32 byte Ed25519 private key for OAuth assertions and DPoP, base64
    agent_id    assigned by the server when a user registers the agent
    grant_token the RFC 8693 subject token a user gave this agent (optional:
                $SEALDROP_GRANT_TOKEN overrides it)

Only `public_bundle()` ever leaves this module, and it holds public keys only.
"""
import json
import os
import pathlib
from dataclasses import dataclass

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat, PrivateFormat, NoEncryption

from . import crypto_cli
from .crypto_cli import b64d, b64e

_DEFAULT_HOME = pathlib.Path(__file__).resolve().parents[1] / "state"


def home() -> pathlib.Path:
    return pathlib.Path(os.environ.get("SEALDROP_AGENT_HOME") or _DEFAULT_HOME)


@dataclass(repr=False)  # repr=False: an accidental print/log never shows keys
class AgentIdentity:
    name: str
    secret: str  # base64 SealDrop identity
    auth_key: Ed25519PrivateKey
    agent_id: str = ""
    grant_token: str = ""
    kem_pk: str = ""
    sig_vk: str = ""

    def __repr__(self) -> str:
        return f"AgentIdentity(name={self.name!r}, agent_id={self.agent_id!r}, keys=<hidden>)"

    def auth_public_raw(self) -> bytes:
        return self.auth_key.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)

    def public_bundle(self) -> dict:
        """What the user pastes into SealDrop to register this agent: public keys only."""
        return {"name": self.name, "kem_pk": self.kem_pk, "sig_vk": self.sig_vk, "auth_key": b64e(self.auth_public_raw())}

    def save(self) -> None:
        d = home()
        d.mkdir(parents=True, exist_ok=True)
        path = d / "agent.json"
        raw = self.auth_key.private_bytes(Encoding.Raw, PrivateFormat.Raw, NoEncryption())
        data = {
            "name": self.name, "secret": self.secret, "auth_key": b64e(raw),
            "agent_id": self.agent_id, "grant_token": self.grant_token,
            "kem_pk": self.kem_pk, "sig_vk": self.sig_vk,
        }
        # Create with owner-only permissions before writing any secret into it.
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(data, f)

    @classmethod
    def create(cls, name: str) -> "AgentIdentity":
        k = crypto_cli.keygen()  # X-Wing + ML-DSA-65, generated by the Rust core
        ident = cls(name=name, secret=k["secret"], auth_key=Ed25519PrivateKey.generate(),
                    kem_pk=k["kem_pk"], sig_vk=k["sig_vk"])
        ident.save()
        return ident

    @classmethod
    def load(cls) -> "AgentIdentity":
        data = json.loads((home() / "agent.json").read_text(encoding="utf-8"))
        ident = cls(
            name=data["name"], secret=data["secret"],
            auth_key=Ed25519PrivateKey.from_private_bytes(b64d(data["auth_key"])),
            agent_id=data.get("agent_id", ""), grant_token=data.get("grant_token", ""),
            kem_pk=data.get("kem_pk", ""), sig_vk=data.get("sig_vk", ""),
        )
        ident.grant_token = os.environ.get("SEALDROP_GRANT_TOKEN") or ident.grant_token
        return ident
